function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === 'node_modules' || e.name === '.html-preview' || e.name.startsWith('.')) continue;
      walk(p, out);
    } else if (e.name.endsWith('.md')) {
      out.push(p);
    }
  }
  return out;
}

function toHtml(md, title) {
  const body = marked.parse(md);
  return `<!doctype html>
<html lang="vi">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width,initial-scale=1">
  <title>${title}</title>
  <style>${CSS}</style>
</head>
<body>
  ${body}
  <hr>
  <p class="footer">Generated by md2html · ${new Date().toLocaleString('vi-VN')}</p>
</body>
</html>`;
}

let files = [];
if (targetArg) {
  const abs = path.resolve(ROOT, targetArg);
  if (!fs.existsSync(abs)) {
    console.error(`❌ Target does not exist: ${targetArg}`);
    process.exit(1);
  }
  const stat = fs.statSync(abs);
  if (stat.isDirectory()) {
    files = walk(abs);
  } else {
    files = [abs];
  }
} else {
  const srcDir = resolveSourceDir();
  if (!fs.existsSync(srcDir)) {
    console.error(`❌ Documents directory not found: ${srcDir}`);
    process.exit(1);
  }
  files = walk(srcDir);
}

if (files.length === 0) {
  console.log('⚠️ No markdown (.md) files found to convert.');
  process.exit(0);
}

for (const f of files) {
  const outFile = f.replace(/\.md$/i, '.html');
  const html = toHtml(fs.readFileSync(f, 'utf8'), path.basename(f));
  fs.writeFileSync(outFile, html);
  console.log(`✓ ${path.relative(ROOT, f)} -> ${path.relative(ROOT, outFile)}`);
}

console.log(`\n🎉 Conversion complete! ${files.length} file(s) converted to HTML.`);

if (shouldOpen && files.length === 1) {
  const outFile = files[0].replace(/\.md$/i, '.html');
  const { execSync } = await import('child_process');
  try {
    const cmd = process.platform === 'darwin' ? 'open' : process.platform === 'win32' ? 'start' : 'xdg-open';
    execSync(`${cmd} "${outFile}"`);
    console.log('Opened file in your default browser.');
  } catch {}
}
